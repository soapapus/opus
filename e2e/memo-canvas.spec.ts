import { expect, test } from '@playwright/test'
import { openApp, goMemo, assertNoErrors } from './helpers'

test('목록과 캔버스가 분리되고 태그 변경·재선택·새로고침 후 본문이 유지된다', async ({ page }) => {
  const errors = await openApp(page)
  await goMemo(page)
  await page.getByRole('button', { name: '새 메모', exact: true }).first().click()
  await page.getByRole('textbox', { name: '메모 제목' }).fill('분리된 캔버스 저장 검사')
  await page.locator('.tiptap').fill('계속 남아야 할 본문')
  await page.getByPlaceholder('+ 태그').fill('새 분류')
  await page.getByPlaceholder('+ 태그').press('Enter')
  await expect(page.locator('.ed-foot')).toContainText('저장됨')
  await expect(page.locator('.memo-list .editor')).toHaveCount(0)
  await expect(page.locator('.memo-canvas .editor')).toHaveCount(1)
  await page.locator('.arow-b').first().click()
  await page.locator('.arow-b', { hasText: '분리된 캔버스 저장 검사' }).click()
  await expect(page.locator('.tiptap')).toContainText('계속 남아야 할 본문')
  await page.reload()
  await goMemo(page)
  await page.locator('.arow-b', { hasText: '분리된 캔버스 저장 검사' }).click()
  await expect(page.locator('.tiptap')).toContainText('계속 남아야 할 본문')
  assertNoErrors(errors)
})

test('빈 줄의 슬래시 메뉴에서 체크리스트·콜아웃을 만들고 일반 문장의 / 는 메뉴를 열지 않는다', async ({ page }) => {
  const errors = await openApp(page)
  await goMemo(page)
  await page.getByRole('button', { name: '새 메모', exact: true }).first().click()
  await page.locator('.tiptap').fill('/')
  await expect(page.getByRole('listbox', { name: '블록 추가' })).toBeVisible()
  await page.getByRole('option', { name: /체크리스트/ }).click()
  await page.locator('.tiptap').pressSequentially('확인할 항목')
  await expect(page.locator('.tiptap input[type="checkbox"]')).toHaveCount(1)
  await page.locator('.tiptap').press('Enter')
  await page.locator('.tiptap').press('Enter')
  await page.locator('.tiptap').pressSequentially('/')
  await page.getByRole('option', { name: /콜아웃/ }).click()
  await page.locator('.tiptap').pressSequentially('중요한 내용')
  await expect(page.locator('.tiptap blockquote')).toContainText('중요한 내용')
  await page.locator('.tiptap').fill('주소 / 일반 문장')
  await expect(page.getByRole('listbox', { name: '블록 추가' })).toHaveCount(0)
  assertNoErrors(errors)
})

test('텍스트를 선택할 때만 서식 도구가 나타나고 굵게가 저장된다', async ({ page }) => {
  const errors = await openApp(page)
  await goMemo(page)
  await page.getByRole('button', { name: '새 메모', exact: true }).first().click()
  await page.locator('.tiptap').fill('선택할 텍스트')
  await expect(page.getByRole('toolbar')).toHaveCount(0)
  await page.locator('.tiptap').press('Control+a')
  await expect(page.getByRole('toolbar', { name: '선택한 글 서식' })).toBeVisible()
  await page.getByRole('button', { name: '굵게', exact: true }).click()
  await expect(page.locator('.tiptap strong')).toHaveText('선택할 텍스트')
  await page.locator('.tiptap').press('ArrowRight')
  await expect(page.getByRole('toolbar')).toHaveCount(0)
  assertNoErrors(errors)
})

test('캘린더를 접고 펴며 체크리스트 핸들을 날짜로 끌면 연결된 일정을 만든다', async ({ page }) => {
  const errors = await openApp(page)
  await goMemo(page)
  await page.getByRole('button', { name: '새 메모', exact: true }).first().click()
  await page.locator('.tiptap').fill('/')
  await page.getByRole('option', { name: /체크리스트/ }).click()
  await page.locator('.tiptap').pressSequentially('일정으로 보낼 작업')
  await expect(page.locator('.memo-drawer')).toHaveCount(0)
  await page.getByRole('button', { name: '캘린더 패널' }).click()
  await page.getByRole('button', { name: '일정으로 보낼 작업 일정으로 끌기' }).dragTo(page.locator('.task-calendar button[data-date="2026-11-06"]'))
  await expect(page.getByRole('status')).toContainText('11월 6일에 일정을 만들었어요')
  await expect(page.locator('.tiptap')).toContainText('일정으로 보낼 작업')
  const events = await page.evaluate(() => window.api.notesByDate('2026-11-06'))
  expect(events.some(n => n.title === '일정으로 보낼 작업' && n.links.length === 1)).toBe(true)
  await page.keyboard.press('Control+Shift+c')
  await expect(page.locator('.memo-drawer')).toHaveCount(0)
  assertNoErrors(errors)
})

